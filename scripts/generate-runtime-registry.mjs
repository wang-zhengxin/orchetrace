import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const registryPath = path.join(root, "runtimes", "registry.json");
const registry = JSON.parse(await readFile(registryPath, "utf8"));
validateRegistry(registry);

const outputs = new Map([
  [path.join(root, "packages", "protocol-ts", "src", "generated-runtime-registry.ts"), renderTypeScript(registry.runtimes)],
  [path.join(root, "apps", "web", "generated-runtime-registry.js"), renderWeb(registry.runtimes)],
  [path.join(root, "crates", "protocol", "src", "generated_runtime_registry.rs"), renderRust(registry.runtimes)],
]);

const checking = process.argv.includes("--check");
const stale = [];
for (const [outputPath, content] of outputs) {
  if (checking) {
    const existing = await readFile(outputPath, "utf8").catch(() => "");
    if (existing !== content) stale.push(path.relative(root, outputPath));
  } else {
    await writeFile(outputPath, content);
  }
}

if (stale.length) {
  throw new Error(`generated runtime registry is stale: ${stale.join(", ")}; run npm run runtime:generate`);
}
if (!checking) console.log(`Generated ${outputs.size} runtime registry targets.`);

function validateRegistry(value) {
  if (!value || value.schema_version !== 1 || !Array.isArray(value.runtimes)) {
    throw new Error("runtime registry must use schema_version 1 and contain runtimes[]");
  }
  const identities = new Set();
  const capabilities = new Set(["passive", "stream", "subagents", "tools", "usage", "hooks"]);
  for (const runtime of value.runtimes) {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(runtime.id)) throw new Error(`invalid runtime id: ${runtime.id}`);
    if (!runtime.label || !runtime.short_label || runtime.short_label.length > 12) throw new Error(`invalid labels for ${runtime.id}`);
    if (!/^#[0-9a-fA-F]{6}$/.test(runtime.accent)) throw new Error(`invalid accent for ${runtime.id}`);
    if (!Array.isArray(runtime.aliases) || !Array.isArray(runtime.capabilities)) throw new Error(`invalid arrays for ${runtime.id}`);
    for (const identity of [runtime.id, ...runtime.aliases]) {
      if (identities.has(identity)) throw new Error(`duplicate runtime identity: ${identity}`);
      identities.add(identity);
    }
    for (const capability of runtime.capabilities) {
      if (!capabilities.has(capability)) throw new Error(`unknown capability ${capability} for ${runtime.id}`);
    }
    for (const field of ["package", "entrypoint", "script_env", "sessions_env", "directory_flag", "state_directory"]) {
      if (typeof runtime.observer?.[field] !== "string" || !runtime.observer[field]) throw new Error(`missing observer.${field} for ${runtime.id}`);
    }
  }
}

function renderTypeScript(runtimes) {
  return `// @generated by scripts/generate-runtime-registry.mjs; do not edit.\nexport const GENERATED_RUNTIME_DESCRIPTORS = ${JSON.stringify(runtimes.map(toCamelDescriptor), null, 2)} as const;\n`;
}

function renderWeb(runtimes) {
  return `// @generated by scripts/generate-runtime-registry.mjs; do not edit.\nexport const GENERATED_RUNTIME_DESCRIPTORS = Object.freeze(${JSON.stringify(runtimes.map(toCamelDescriptor), null, 2)});\n`;
}

function toCamelDescriptor(runtime) {
  return {
    id: runtime.id,
    label: runtime.label,
    shortLabel: runtime.short_label,
    accent: runtime.accent,
    aliases: runtime.aliases,
    sessionDirectory: runtime.session_directory,
    capabilities: runtime.capabilities,
    observer: {
      package: runtime.observer.package,
      entrypoint: runtime.observer.entrypoint,
      scriptEnv: runtime.observer.script_env,
      sessionsEnv: runtime.observer.sessions_env,
      directoryFlag: runtime.observer.directory_flag,
      stateDirectory: runtime.observer.state_directory,
    },
  };
}

function renderRust(runtimes) {
  const rows = runtimes.map((runtime) => `    RuntimeDescriptor {\n        id: ${rust(runtime.id)},\n        label: ${rust(runtime.label)},\n        short_label: ${rust(runtime.short_label)},\n        accent: ${rust(runtime.accent)},\n        aliases: &[${runtime.aliases.map(rust).join(", ")}],\n        session_directory: ${rust(runtime.session_directory)},\n        capabilities: &[${runtime.capabilities.map(rust).join(", ")}],\n        observer: RuntimeObserverDescriptor {\n            package: ${rust(runtime.observer.package)},\n            entrypoint: ${rust(runtime.observer.entrypoint)},\n            script_env: ${rust(runtime.observer.script_env)},\n            sessions_env: ${rust(runtime.observer.sessions_env)},\n            directory_flag: ${rust(runtime.observer.directory_flag)},\n            state_directory: ${rust(runtime.observer.state_directory)},\n        },\n    }`).join(",\n");
  return `// @generated by scripts/generate-runtime-registry.mjs; do not edit.\nuse super::{RuntimeDescriptor, RuntimeObserverDescriptor};\n\npub static REGISTERED_RUNTIMES: &[RuntimeDescriptor] = &[\n${rows},\n];\n\npub fn runtime_descriptor(runtime: &str) -> Option<&'static RuntimeDescriptor> {\n    REGISTERED_RUNTIMES\n        .iter()\n        .find(|descriptor| descriptor.id == runtime || descriptor.aliases.contains(&runtime))\n}\n`;
}

function rust(value) {
  return JSON.stringify(value);
}
